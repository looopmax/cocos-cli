'use strict';

/**
 * Compile every runtime JavaScript file in dist/bundle/ to V8 bytecode.
 *
 * 构建产物已由 workflow/build-bundle.js 打包为少量 bundle 文件，
 * 此处只对这些 bundle 文件做字节码保护。每个 .js 保留一个 CommonJS
 * loader，保证 require/import 行为不变；原始源码存为 .source.js 备查。
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const bytenode = require('bytenode');

const projectRoot = path.resolve(__dirname, '..');
const runtimeRoots = [
    path.join(projectRoot, 'dist', 'bundle'),
];
const workerFile = path.join(__dirname, 'build-bytenode-worker.js');
const generatedLoaderMarker = 'Generated by workflow/build-bytenode.js.';

function resolveElectronPath() {
    const electronName = process.platform === 'win32' ? 'electron.exe' : 'electron';
    const pinkName = process.platform === 'win32' ? 'PinK.exe' : 'PinK';
    const candidates = [
        process.env.COCOS_ELECTRON_PATH,
        path.resolve(projectRoot, '..', 'PinK', 'node_modules', 'electron', 'dist', electronName),
        path.resolve(projectRoot, '..', 'PinK', '.build', 'electron', pinkName),
    ].filter(Boolean);

    return candidates.find((candidate) => fs.existsSync(candidate));
}

function collectJavaScriptFiles(directory) {
    const files = [];
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
        const file = path.join(directory, entry.name);
        if (entry.isDirectory()) {
            if (entry.name === 'node_modules' || entry.name === '.git') continue;
            files.push(...collectJavaScriptFiles(file));
        } else if (
            entry.isFile()
            && entry.name.endsWith('.js')
            && !entry.name.endsWith('.source.js')
            && !entry.name.endsWith('.loader.js')
        ) {
            files.push(file);
        }
    }
    return files;
}

function collectRuntimeFiles() {
    const files = [];
    for (const root of runtimeRoots) {
        if (!fs.existsSync(root)) {
            console.warn(`[build-bytenode] runtime root not found, skipped: ${root}`);
            continue;
        }
        files.push(...collectJavaScriptFiles(root));
    }
    return files.sort();
}

function isEsmSource(file) {
    // bundle 产物由 esbuild 生成且 format=cjs，不可能是 ESM。
    // 保留函数以兼容手动放置的 ESM 文件判断。
    if (file.includes(path.join('dist', 'bundle'))) {
        return false;
    }
    const source = fs.readFileSync(file, 'utf8').replace(/^#![^\r\n]*(?:\r?\n|$)/, '');
    return /^\s*(?:import\s|export\s)/m.test(source);
}

function restoreAndSnapshot(files) {
    for (const file of files) {
        const sourceSnapshot = file.slice(0, -3) + '.source.js';
        const current = fs.readFileSync(file, 'utf8');
        if (current.includes(generatedLoaderMarker)) {
            if (!fs.existsSync(sourceSnapshot)) {
                throw new Error(`[build-bytenode] source snapshot not found: ${sourceSnapshot}`);
            }
            fs.copyFileSync(sourceSnapshot, file);
        }
        fs.copyFileSync(file, sourceSnapshot);
    }
}

function restoreOnly(files) {
    let restored = 0;
    for (const file of files) {
        const sourceSnapshot = file.slice(0, -3) + '.source.js';
        if (!fs.existsSync(sourceSnapshot)) continue;
        const current = fs.readFileSync(file, 'utf8');
        if (!current.includes(generatedLoaderMarker)) continue;
        fs.copyFileSync(sourceSnapshot, file);
        fs.rmSync(file.slice(0, -3) + '.jsc', { force: true });
        restored++;
    }
    console.log(`[build-bytenode] restored ${restored} generated JavaScript loaders`);
}

function writeLoader(file) {
    const baseName = path.basename(file, '.js');
    const bytecodeName = `./${baseName}.jsc`;
    const sourceName = `./${baseName}.source.js`;
    const loader = `'use strict';\n\n// ${generatedLoaderMarker}\nconst Module = require('module');\nconst path = require('path');\nconst bytecodeFile = path.join(__dirname, ${JSON.stringify(`${baseName}.jsc`)});\nrequire('bytenode');\n\ntry {\n    // Execute into the current .js module object. This preserves Node's\n    // original require.cache identity and circular-dependency semantics.\n    Module._extensions['.jsc'](module, bytecodeFile);\n} catch (error) {\n    // A .jsc file is tied to the V8 runtime that produced it.\n    if (!/cachedDataRejected|incompatible cached data/i.test(String(error && error.message))) {\n        throw error;\n    }\n    module.exports = require(${JSON.stringify(sourceName)});\n}\n`;
    fs.writeFileSync(file, loader, 'utf8');
}

function writeLoaders(files) {
    for (const file of files) {
        writeLoader(file);
    }
}

function compileWithNode(files) {
    for (const file of files) {
        const source = fs.readFileSync(file, 'utf8').replace(/^#![^\r\n]*(?:\r?\n|$)/, '');
        const bytecode = bytenode.compileCode(require('module').wrap(source));
        fs.writeFileSync(file.slice(0, -3) + '.jsc', bytecode);
    }
}

function compileWithElectron(files, electronPath) {
    const manifestRoot = runtimeRoots.find((root) => fs.existsSync(root)) || projectRoot;
    const manifestFile = path.join(manifestRoot, '.bytenode-files.json');
    fs.writeFileSync(manifestFile, JSON.stringify(files), 'utf8');
    try {
        const result = spawnSync(electronPath, [
            '--no-sandbox',
            '--disable-gpu',
            workerFile,
            manifestFile,
        ], {
            cwd: projectRoot,
            stdio: 'inherit',
            windowsHide: true,
        });
        if (result.error) throw result.error;
        if (result.status !== 0) {
            throw new Error(`Electron bytecode worker exited with code ${result.status}`);
        }
    } finally {
        fs.rmSync(manifestFile, { force: true });
    }
}

async function main() {
    const allFiles = collectRuntimeFiles();
    if (process.argv.includes('--restore')) {
        restoreOnly(allFiles);
        return;
    }
    const files = allFiles.filter((file) => !isEsmSource(file));
    const skippedEsm = allFiles.length - files.length;
    if (files.length === 0) {
        throw new Error(`[build-bytenode] no JavaScript files found in runtime roots: ${runtimeRoots.join(', ')}`);
    }
    if (skippedEsm > 0) {
        console.warn(`[build-bytenode] skipped ${skippedEsm} ESM files; Bytenode CommonJS loaders cannot load ESM bytecode.`);
    }

    restoreAndSnapshot(files);
    for (const file of files) {
        fs.rmSync(file.slice(0, -3) + '.jsc', { force: true });
    }

    const electronPath = resolveElectronPath();
    if (electronPath) {
        console.log(`[build-bytenode] compiling ${files.length} JavaScript files with Electron: ${electronPath}`);
        compileWithElectron(files, electronPath);
    } else {
        console.warn('[build-bytenode] PinK Electron was not found; compiling with the current Node runtime. Set COCOS_ELECTRON_PATH for production bytecode.');
        compileWithNode(files);
    }

    writeLoaders(files);
    console.log(`[build-bytenode] generated ${files.length} .jsc files and compatibility loaders`);
}

main().catch((error) => {
    console.error('[build-bytenode] failed:', error);
    process.exitCode = 1;
});
